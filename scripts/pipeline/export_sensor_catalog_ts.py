#!/usr/bin/env python3
"""Export sensor_catalog.json → TypeScript module for the web app."""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "data" / "raw" / "sensor_catalog.json"
OUT = ROOT / "examples" / "web" / "src" / "features" / "table" / "sensorCatalog.generated.ts"


def main() -> int:
    data = json.loads(SRC.read_text(encoding="utf-8"))
    sensors = data.get("sensors") or {}
    # Compact records for the browser
    compact: dict[str, dict] = {}
    for key, entry in sensors.items():
        compact[key] = {
            k: entry[k]
            for k in ("optical_format", "diag_mm", "pixel_pitch_um", "mp", "role_hint")
            if entry.get(k) is not None
        }
    aliases = data.get("aliases") or {}
    body = (
        "/* Generated by scripts/pipeline/export_sensor_catalog_ts.py — do not edit. */\n"
        "export type SensorCatalogEntry = {\n"
        "  optical_format?: string;\n"
        "  diag_mm?: number;\n"
        "  pixel_pitch_um?: number;\n"
        "  mp?: number;\n"
        "  role_hint?: string;\n"
        "};\n\n"
        f"export const TYPE1_MM = {data.get('type1_mm', 16)};\n\n"
        f"export const SENSOR_CATALOG: Record<string, SensorCatalogEntry> = {json.dumps(compact, indent=2)};\n\n"
        f"export const SENSOR_ALIASES: Record<string, string> = {json.dumps(aliases, indent=2)};\n"
    )
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(body, encoding="utf-8")
    print(f"Wrote {OUT} ({len(compact)} sensors)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
